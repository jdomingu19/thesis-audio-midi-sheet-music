/**
 * Catálogo de instrumentos de reproducción. Solo datos (sin imports): lo
 * consumen tanto la app como scripts/download-samples.mjs.
 *
 * `notes` son los nombres de archivo (sin extensión) de las muestras; las
 * alteraciones usan "s" (Ds4 = D#4). Tone.Sampler interpola las notas
 * intermedias. `release` en segundos; `volumeDb` ajusta el nivel relativo.
 */

export const DEFAULT_INSTRUMENT_ID = "grand-piano";

const TONEJS_AUDIO_CDN = "https://tonejs.github.io/audio/";
const TONEJS_AUDIO_RAW =
  "https://raw.githubusercontent.com/Tonejs/audio/master/";
const INSTRUMENTS_CDN =
  "https://cdn.jsdelivr.net/gh/nbrosowsky/tonejs-instruments@master/samples/";
const INSTRUMENTS_RAW =
  "https://raw.githubusercontent.com/nbrosowsky/tonejs-instruments/master/samples/";

function libraryInstrument({
  id,
  label,
  description,
  folder,
  notes,
  release,
  volumeDb = 0,
}) {
  return {
    id,
    label,
    description,
    kind: "sampler",
    folder,
    notes,
    release,
    volumeDb,
    remoteBase: `${INSTRUMENTS_CDN}${folder}/`,
    downloadBase: `${INSTRUMENTS_RAW}${folder}/`,
  };
}

